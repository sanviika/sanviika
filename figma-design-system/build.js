#!/usr/bin/env node
// Builds code.js (the Figma plugin bundle) and developer exports:
//   tokens/design-tokens.json  (W3C Design Tokens format, light + dark)
//   tokens/variables.css       (CSS custom properties, [data-theme="dark"])
//   docs/DESIGN_SYSTEM.md      (style guide generated from docs-content.js)
const fs = require('fs');
const path = require('path');

const SRC = ['tokens.js', 'docs-content.js', 'core.js', 'foundations.js', 'atoms.js', 'molecules.js', 'organisms.js', 'main.js'];
const dir = __dirname;
const header = '// Northstar B2B Design System — Figma plugin bundle. GENERATED by build.js — edit src/*.js instead.\n';
const bundle = header + SRC.map(function (f) { return '\n// ---- src/' + f + ' ----\n' + fs.readFileSync(path.join(dir, 'src', f), 'utf8'); }).join('\n');
fs.writeFileSync(path.join(dir, 'code.js'), bundle);

// Evaluate the token + docs modules for exports.
const ctx = new Function(fs.readFileSync(path.join(dir, 'src/tokens.js'), 'utf8') + '\n' + fs.readFileSync(path.join(dir, 'src/docs-content.js'), 'utf8') +
  '\nreturn { DS_NAME, DS_VERSION, PRIMITIVES, SEMANTIC, DIMENSIONS, TYPE_SCALE, FONT_STYLE, ELEVATION, GRIDS, DOCS, resolveTokenHex };')();

// ---------------------------------------------------------------- JSON tokens
const W = { primitive: {}, light: {}, dark: {}, dimension: { comfortable: {}, compact: {} }, typography: {}, shadow: {} };
const setPath = function (obj, name, val) {
  const parts = name.split('/'); let o = obj;
  parts.slice(0, -1).forEach(function (p) { o = o[p] = o[p] || {}; });
  o[parts[parts.length - 1]] = val;
};
Object.keys(ctx.PRIMITIVES).forEach(function (fam) {
  Object.keys(ctx.PRIMITIVES[fam]).forEach(function (s) { setPath(W.primitive, fam + '/' + s, { $type: 'color', $value: ctx.PRIMITIVES[fam][s] }); });
});
const ref = function (r) { return /^[a-z]+\/\d+$/.test(r) ? '{primitive.' + r.replace('/', '.') + '}' : ctx.resolveTokenHex(r); };
ctx.SEMANTIC.forEach(function (r) {
  setPath(W.light, r[0], { $type: 'color', $value: ref(r[1]), $description: r[3] });
  setPath(W.dark, r[0], { $type: 'color', $value: ref(r[2]), $description: r[3] });
});
ctx.DIMENSIONS.forEach(function (d) {
  setPath(W.dimension.comfortable, d[0], { $type: 'dimension', $value: d[1] + 'px', $description: d[3] });
  setPath(W.dimension.compact, d[0], { $type: 'dimension', $value: d[2] + 'px', $description: d[3] });
});
ctx.TYPE_SCALE.forEach(function (t) {
  setPath(W.typography, t[0], { $type: 'typography', $description: t[7], $value: {
    fontFamily: t[1] === 'mono' ? 'Roboto Mono' : 'Inter', fontWeight: { regular: 400, medium: 500, semibold: 600, bold: 700 }[t[1] === 'mono' ? 'regular' : t[2]],
    fontSize: t[3] + 'px', lineHeight: t[4] + 'px', letterSpacing: (t[5] / 100) + 'em', textTransform: t[6] ? 'uppercase' : 'none',
  } });
});
ctx.ELEVATION.forEach(function (e) {
  setPath(W.shadow, e[0].replace(/ /g, '-'), { $type: 'shadow', $description: e[2], $value: e[1].map(function (l) { return { offsetX: l[0] + 'px', offsetY: l[1] + 'px', blur: l[2] + 'px', spread: l[3] + 'px', color: '{color.' + l[4].replace('/', '.') + '}' }; }) });
});
fs.mkdirSync(path.join(dir, 'tokens'), { recursive: true });
fs.writeFileSync(path.join(dir, 'tokens/design-tokens.json'), JSON.stringify({ $name: ctx.DS_NAME, $version: ctx.DS_VERSION, primitive: W.primitive, color: { light: W.light, dark: W.dark }, dimension: W.dimension, typography: W.typography, shadow: W.shadow }, null, 2));

// ---------------------------------------------------------------- CSS
const cssVar = function (n) { return '--ns-' + n.replace(/\//g, '-'); };
const cssVal = function (r) { return /^[a-z]+\/\d+$/.test(r) ? 'var(' + cssVar('color/' + r) + ')' : ctx.resolveTokenHex(r); };
let css = '/* ' + ctx.DS_NAME + ' ' + ctx.DS_VERSION + ' — generated by build.js */\n:root {\n';
Object.keys(ctx.PRIMITIVES).forEach(function (fam) { Object.keys(ctx.PRIMITIVES[fam]).forEach(function (s) { css += '  ' + cssVar('color/' + fam + '/' + s) + ': ' + ctx.PRIMITIVES[fam][s] + ';\n'; }); });
ctx.SEMANTIC.forEach(function (r) { css += '  ' + cssVar(r[0]) + ': ' + cssVal(r[1]) + ';\n'; });
ctx.DIMENSIONS.forEach(function (d) { css += '  ' + cssVar(d[0]) + ': ' + d[1] + 'px;\n'; });
ctx.TYPE_SCALE.forEach(function (t) {
  const w = { regular: 400, medium: 500, semibold: 600, bold: 700 }[t[1] === 'mono' ? 'regular' : t[2]];
  css += '  ' + cssVar('font/' + t[0].toLowerCase()) + ': ' + w + ' ' + t[3] + 'px/' + t[4] + 'px ' + (t[1] === 'mono' ? '"Roboto Mono", ui-monospace, monospace' : 'Inter, system-ui, sans-serif') + ';\n';
});
css += '}\n\n[data-theme="dark"] {\n';
ctx.SEMANTIC.forEach(function (r) { css += '  ' + cssVar(r[0]) + ': ' + cssVal(r[2]) + ';\n'; });
css += '}\n\n[data-density="compact"] {\n';
ctx.DIMENSIONS.filter(function (d) { return d[1] !== d[2]; }).forEach(function (d) { css += '  ' + cssVar(d[0]) + ': ' + d[2] + 'px;\n'; });
css += '}\n';
fs.writeFileSync(path.join(dir, 'tokens/variables.css'), css);

// ---------------------------------------------------------------- Markdown style guide
const D = ctx.DOCS;
const order = [
  ['Foundations', ['colors', 'typography', 'spacing', 'radius', 'elevation', 'grid', 'icons']],
  ['Atoms', ['button', 'iconButton', 'input', 'textarea', 'checkbox', 'radio', 'toggle', 'badge', 'tag', 'avatar', 'tooltip', 'link', 'divider', 'spinner', 'progress']],
  ['Molecules', ['menu', 'select', 'formField', 'search', 'tabs', 'breadcrumb', 'pagination', 'alert', 'toast', 'statCard', 'navItem', 'table', 'card', 'emptyState']],
  ['Organisms', ['topNav', 'sidebar', 'pageHeader', 'kpi', 'filterBar', 'dataTable', 'modal', 'formSection', 'sourceImport']],
  ['Templates', ['templates']],
];
const list = function (title, items) { return items && items.length ? '**' + title + '**\n\n' + items.map(function (i) { return '- ' + i; }).join('\n') + '\n\n' : ''; };
let md = '# ' + ctx.DS_NAME + ' Design System — Style Guide (v' + ctx.DS_VERSION + ')\n\n';
md += '> Generated from `src/docs-content.js` and `src/tokens.js` by `build.js`. The same content is rendered on every page of the Figma file.\n\n';
md += '## Contents\n\n' + order.map(function (g) { return '- **' + g[0] + '**: ' + g[1].map(function (k) { return '[' + D[k].title + '](#' + D[k].title.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-') + ')'; }).join(' · '); }).join('\n') + '\n\n';
md += '## Token architecture\n\n| Tier | Collection | Modes | Example | Applied by |\n|---|---|---|---|---|\n';
md += '| Primitive | `Primitives` | Value | `brand/600` | Semantic tokens only (hidden scopes) |\n';
md += '| Semantic colour | `Color` | Light, Dark | `bg/brand` | Designers & components |\n';
md += '| Dimension | `Dimensions` | Comfortable, Compact | `space/400`, `size/control-md` | Auto-layout padding, gap, radius, size |\n';
md += '| Typography | `Typography` | Value | `font-size/14` | Text styles |\n\n';
md += '### Semantic colours\n\n| Token | Light | Dark | Usage |\n|---|---|---|---|\n';
ctx.SEMANTIC.forEach(function (r) { md += '| `' + r[0] + '` | `' + r[1] + '` | `' + r[2] + '` | ' + r[3] + ' |\n'; });
md += '\n### Typography\n\n| Style | Font | Size / Line | Tracking | Usage |\n|---|---|---|---|---|\n';
ctx.TYPE_SCALE.forEach(function (t) { md += '| ' + t[0] + ' | ' + (t[1] === 'mono' ? 'Roboto Mono Regular' : 'Inter ' + ctx.FONT_STYLE[t[2]]) + ' | ' + t[3] + '/' + t[4] + ' | ' + t[5] + '%' + (t[6] ? ' UPPER' : '') + ' | ' + t[7] + ' |\n'; });
md += '\n### Dimensions\n\n| Token | Comfortable | Compact | Usage |\n|---|---|---|---|\n';
ctx.DIMENSIONS.forEach(function (d) { md += '| `' + d[0] + '` | ' + d[1] + ' | ' + d[2] + ' | ' + d[3] + ' |\n'; });
md += '\n### Elevation\n\n| Style | Usage |\n|---|---|\n';
ctx.ELEVATION.forEach(function (e) { md += '| ' + e[0] + ' | ' + e[2] + ' |\n'; });
order.forEach(function (g) {
  md += '\n---\n\n# ' + g[0] + '\n\n';
  g[1].forEach(function (k) {
    const d = D[k];
    md += '## ' + d.title + '\n\n*' + d.category + '* — ' + d.summary + '\n\n';
    md += list('When to use', d.whenToUse) + list('When not to use', d.whenNot) + list('Anatomy', d.anatomy) + list('Do', d.dos) + list('Don’t', d.donts) + list('Accessibility', d.a11y);
  });
});
fs.mkdirSync(path.join(dir, 'docs'), { recursive: true });
fs.writeFileSync(path.join(dir, 'docs/DESIGN_SYSTEM.md'), md);
console.log('Built code.js (' + Math.round(bundle.length / 1024) + ' KB), tokens/design-tokens.json, tokens/variables.css, docs/DESIGN_SYSTEM.md');
